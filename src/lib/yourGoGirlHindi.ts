const hi = (c: ReplyCtx) => (c.name ? `, ${c.name}` : '');

export function phaseLineHindi(c: ReplyCtx): string {
  if (!c.hasCycleData || c.day <= 0) return '';
  switch (c.phase) {
    case 'menstrual':
      return `आप साइकिल के दिन ${c.day} पर हैं — पीरियड के दिन चल रहे हैं।`;
    case 'follicular':
      return `आप दिन ${c.day} पर हैं, पीरियड के बाद वाले फेज़ (फॉलिक्युलर) में, जब एनर्जी आमतौर पर बढ़ती है।`;
    case 'ovulatory':
      return `आप दिन ${c.day} पर हैं, ओव्यूलेशन के आसपास।`;
    case 'luteal':
      return `आप दिन ${c.day} पर हैं, ल्यूटियल फेज़ में — पीरियड से पहले के 1–2 हफ़्ते, जब कई लोगों को PMS होता है।`;
    default:
      return `आप दिन ${c.day} पर हैं, सामान्य से लंबे साइकिल में।`;
  }
}

