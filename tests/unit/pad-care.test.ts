import { timerStatus, suggestedHours, shortGapCount, reminderHours, HOUR_MS, formatElapsed, noteScore } from '@/lib/padCare';
import { usePadCareStore } from '@/store/usePadCareStore';
import { useAppStore } from '@/store/useAppStore';
let pass=0, fail=0;
const ok=(c:boolean,m:string)=>{ if(c){pass++;} else {fail++; console.log('FAIL',m);} };
const t0=Date.UTC(2026,10,18,6,0);
const s={since:t0,mode:'day' as const,product:'pad' as const};
ok(timerStatus(s,4,t0+HOUR_MS).id==='fresh','fresh at 1h');
ok(timerStatus(s,4,t0+3.2*HOUR_MS).id==='soon','soon at 3.2h');
ok(timerStatus(s,4,t0+4*HOUR_MS).id==='due','due at 4h');
ok(timerStatus(s,4,t0+8*HOUR_MS).id==='over','over at 8h');
ok(timerStatus({...s,product:'tampon'},4,t0+8*HOUR_MS).hint.includes('8 hours'),'tampon 8h warning');
ok(reminderHours('pad','night',4)===8,'night pad 8h');
ok(reminderHours('pad','day',10)===6,'pad interval capped at 6');
ok(reminderHours('cup','day',10)===10,'cup allows 10');
ok(suggestedHours('pad','heavy')===3,'heavy pad 3h');
ok(suggestedHours('cup','heavy')===6,'heavy cup 6h');
ok(suggestedHours('pad','light')===4,'light pad 4h');
ok(shortGapCount([{at:t0},{at:t0+HOUR_MS},{at:t0+2*HOUR_MS},{at:t0+3.5*HOUR_MS},{at:t0+9*HOUR_MS}],t0+10*HOUR_MS)===3,'short gaps 3');
ok(formatElapsed(125*60000)==='2h 05m','format');
ok(noteScore({comfort:5,protection:4,skin:'irritated'})===6,'note score');
const st=usePadCareStore.getState();
st.startWear(t0,'day'); usePadCareStore.getState().startWear(t0+60000,'day');
ok(usePadCareStore.getState().changes.length===1,'double tap guard');
usePadCareStore.getState().startWear(t0+3*HOUR_MS,'night');
ok(usePadCareStore.getState().changes.length===2 && usePadCareStore.getState().active?.mode==='night','second change');
usePadCareStore.getState().setIntervalHours(20); ok(usePadCareStore.getState().intervalHours===6,'pad interval clamp');
usePadCareStore.getState().setProduct('cup'); ok(usePadCareStore.getState().intervalHours===8 && usePadCareStore.getState().active?.product==='cup','cup switch');
usePadCareStore.getState().setIntervalHours(11); ok(usePadCareStore.getState().intervalHours===11,'cup 11h');
usePadCareStore.getState().addNote({brand:'  ',product:'pad',comfort:3,protection:3,skin:'fine'}); ok(usePadCareStore.getState().notes.length===0,'empty brand rejected');
usePadCareStore.getState().addNote({brand:'X cotton',product:'pad',comfort:9,protection:0,skin:'fine'}); const n=usePadCareStore.getState().notes[0]; ok(n.comfort===5&&n.protection===1,'rating clamp');
usePadCareStore.getState().toggleChecklist('isi'); ok(usePadCareStore.getState().checklist.includes('isi'),'checklist');
// sign out resets pad care
(async()=>{
await useAppStore.getState().logout?.();
await new Promise(r=>setTimeout(r,50));
ok(usePadCareStore.getState().changes.length===0 && usePadCareStore.getState().active===null && usePadCareStore.getState().notes.length===0,'logout resets pad care');
console.log(`pad: ${pass} passed, ${fail} failed`);
})();
process.exitCode = fail ? 1 : 0;
